function normalizeLanguage(language) {
    return languageCodes.indexOf(language) >= 0 ? language : "en"
}

function tr(language, source, argument) {
    var catalog = messages[normalizeLanguage(language)]
    var text = catalog[source] || messages.en[source] || source
    return argument === undefined ? text : text.replace(/%1/g, function() { return String(argument) })
}
